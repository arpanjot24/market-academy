import { p, ul, ex, table, tip, warn, info, Q, step, check } from './dsl'
import { strategyById } from './strategies'
import type { Block, LessonDef, Level, Step } from './types'

const link = (text: string, href: string): Block => ({ t: 'link', text, href })

function strategyStep(id: string): Step {
  const s = strategyById[id]
  return step('concept', s.name,
    info(`**Horizon:** ${s.horizon}. ${s.idea}`),
    table('Rules', [
      ['Entry', s.entry.join(' · ')],
      ['Exit', s.exit.join(' · ')],
      ['Stop-loss', s.stop],
      ['Reward : risk', s.rr],
      ['Position sizing', s.sizing],
    ]),
    tip(`**Suitable conditions:** ${s.suits}`),
    warn(`**When it fails:** ${s.fails}`),
    p(`**Backtesting:** ${s.backtest}`),
    p(`**Example:** ${s.example}`),
    ...(s.practice ? [link('See it on the practice chart', `#/interpreter/${s.practice}`)] : []),
  )
}

function strategyLesson(id: string, title: string, level: Level, summary: string, ids: string[], extra: Step[], quiz: LessonDef['quiz']): LessonDef {
  return { id, title, level, summary, minutes: ids.length * 4 + 3, steps: [...ids.map(strategyStep), ...extra], quiz }
}

